/* ============================================================
   Generating the Vercel Routing Middleware.

   The middleware is what picks the language for a visitor who
   has not chosen one yet: it reads the country of the incoming
   IP and sends the visitor to the matching language folder.

   It is generated from the locale configuration so that the
   country list and the URL prefixes can never drift apart from
   the rest of the build.

   Vercel runs this file before every request. `next()` from
   @vercel/functions lets the request continue to the static
   file untouched.
   ============================================================ */

import { LOCALES } from './config.mjs';

/** Bot user-agent patterns that must never be redirected. */
const BOT_PATTERN =
  'bot|crawler|spider|crawling|slurp|bingpreview|facebookexternalhit|' +
  'headless|scrapy|semrush|ahrefs|mj12bot|dotbot|blexbot|petalbot|' +
  'gptbot|claudebot|ccbot|bytespider|perplexity|oai-searchbot|' +
  'chatgpt-user|adsbot|applebot|twitterbot|linkedinbot|discordbot|' +
  'telegrambot|whatsapp|preview|python-requests|curl|wget|libwww';

/**
 * Render middleware.ts.
 *
 * @returns {string} the TypeScript source
 */
export function renderMiddleware() {
  const countryToLocale = {};
  for (const locale of LOCALES) {
    for (const country of locale.countries) {
      countryToLocale[country] = locale.code;
    }
  }

  const localeToPrefix = {};
  const localePaths = [];
  for (const locale of LOCALES) {
    localeToPrefix[locale.code] = locale.prefix;
    if (locale.prefix) localePaths.push(`/${locale.prefix}`);
  }

  // The Accept-Language fallback: the primary language subtag of the
  // browser decides, so pt-BR and pt-PT both land on Brazilian
  // Portuguese.
  const languageToLocale = {
    ro: 'ro',
    pt: 'pt-BR',
    es: 'es',
    en: 'en'
  };

  return `/* ============================================================
   Generated by tools/build.mjs — do not edit by hand.
   Run \`node tools/build.mjs\` to regenerate it.

   Vercel Routing Middleware: it picks the language for a visitor
   who has not chosen one yet, based on the country of their IP.
   A visitor who picks a language in the switcher gets a cookie,
   and that choice always wins over the country.
   ============================================================ */

import { geolocation, next } from '@vercel/functions';

const COOKIE_NAME = 'digital-online-lang';
const COOKIE_MAX_AGE = 60 * 60 * 24 * 180;

/** ISO-3166 alpha-2 country code -> locale code. */
const COUNTRY_TO_LOCALE: Record<string, string> = ${JSON.stringify(countryToLocale, null, 2).replace(/\n/g, '\n')};

/** Locale code -> path prefix. Romanian lives at the site root. */
const LOCALE_PREFIX: Record<string, string> = ${JSON.stringify(localeToPrefix, null, 2).replace(/\n/g, '\n')};

/** Path prefixes that already hold a language. */
const LOCALE_PATHS = ${JSON.stringify(localePaths)};

/** Browser language tag -> locale code. */
const LANGUAGE_TO_LOCALE: Record<string, string> = ${JSON.stringify(languageToLocale, null, 2).replace(/\n/g, '\n')};

const BOT_PATTERN = new RegExp(${JSON.stringify(BOT_PATTERN)}, 'i');

export const config = {
  runtime: 'nodejs',
  /* Only the HTML pages need the language decision. */
  matcher: [
    '/((?!css/|js/|img/|fonts/|robots\\\\.txt|sitemap\\\\.xml|llms\\\\.txt|favicon\\\\.ico|apple-touch-icon\\\\.png|site\\\\.webmanifest|google16298c737d30f4e5\\\\.html).*)'
  ]
};

/** Read one cookie out of the Cookie header. */
function readCookie(header: string | null, name: string): string | undefined {
  if (!header) return undefined;
  for (const part of header.split(';')) {
    const index = part.indexOf('=');
    if (index === -1) continue;
    if (part.slice(0, index).trim() !== name) continue;
    return decodeURIComponent(part.slice(index + 1).trim());
  }
  return undefined;
}

/** Is the path already inside a language folder? */
function hasLocalePrefix(path: string): boolean {
  return LOCALE_PATHS.some((prefix) => path === prefix || path.startsWith(prefix + '/'));
}

/** Does the path point at a file that is not an HTML page? */
function isAsset(path: string): boolean {
  const name = path.split('/').pop() || '';
  if (!name.includes('.')) return false;
  return !name.endsWith('.html');
}

/** The locale the browser asks for, by Accept-Language. */
function localeFromAcceptLanguage(header: string | null): string | undefined {
  if (!header) return undefined;

  const entries = header
    .split(',')
    .map((part) => {
      const [tag, ...params] = part.trim().split(';');
      const quality = params
        .map((p) => p.trim())
        .find((p) => p.startsWith('q='));
      const q = quality ? Number.parseFloat(quality.slice(2)) : 1;
      return { tag: tag.trim().toLowerCase(), q: Number.isNaN(q) ? 0 : q };
    })
    .filter((entry) => entry.tag && entry.q > 0)
    .sort((a, b) => b.q - a.q);

  for (const entry of entries) {
    const hit = LANGUAGE_TO_LOCALE[entry.tag] ?? LANGUAGE_TO_LOCALE[entry.tag.split('-')[0]];
    if (hit) return hit;
  }
  return undefined;
}

/** Send the visitor to the given language and remember the choice. */
function redirect(request: Request, url: URL, prefix: string, locale: string): Response {
  const path = url.pathname === '/' ? '/' : url.pathname;
  const target = new URL(\`\${prefix}\${path}\${url.search}\`, request.url);
  return new Response(null, {
    status: 302,
    headers: {
      Location: target.toString(),
      'Set-Cookie': \`\${COOKIE_NAME}=\${locale}; Path=/; Max-Age=\${COOKIE_MAX_AGE}; SameSite=Lax\`
    }
  });
}

export default function middleware(request: Request) {
  const url = new URL(request.url);
  const path = url.pathname;

  /* The visitor already picked a language, or the URL already names
     one: leave it alone. */
  if (hasLocalePrefix(path)) return next();
  if (isAsset(path)) return next();

  /* Crawlers must see the canonical Romanian pages. */
  const userAgent = request.headers.get('user-agent') || '';
  if (BOT_PATTERN.test(userAgent)) return next();

  /* A language chosen in the switcher always wins. */
  const chosen = readCookie(request.headers.get('cookie'), COOKIE_NAME);
  if (chosen && chosen in LOCALE_PREFIX) {
    const prefix = LOCALE_PREFIX[chosen];
    if (!prefix) return next();
    return redirect(request, url, prefix, chosen);
  }

  /* The country of the visitor decides. */
  const { country } = geolocation(request);
  let locale = country ? COUNTRY_TO_LOCALE[country.toUpperCase()] : undefined;

  /* No country match: fall back to the language of the browser. */
  if (!locale) {
    locale = localeFromAcceptLanguage(request.headers.get('accept-language'));
  }

  /* Nothing matched, or the visitor belongs to the Romanian site. */
  if (!locale || !LOCALE_PREFIX[locale]) return next();

  return redirect(request, url, LOCALE_PREFIX[locale], locale);
}
`;
}
