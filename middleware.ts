/** Locale code -> path prefix. Romanian lives at the site root. */
const LOCALE_PREFIX: Record<string, string> = {
  "ro": "",
  "en": "en",
  "es": "es",
  "pt-BR": "pt-br"
};

/** Path prefixes that already hold a language. */
const LOCALE_PATHS = ["/en","/es","/pt-br"];

/** Browser language tag -> locale code. */
const LANGUAGE_TO_LOCALE: Record<string, string> = {
  "ro": "ro",
  "pt": "pt-BR",
  "es": "es",
  "en": "en"
};

